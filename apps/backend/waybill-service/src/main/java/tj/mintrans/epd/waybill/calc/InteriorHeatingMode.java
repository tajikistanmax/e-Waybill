package tj.mintrans.epd.waybill.calc;

/**
 * Режим надбавки на отопление салона ({@code brands.fuel_interior_heating} × часы работы)
 * в пассажирском расчёте (обычная ветка, не Душанбе) — свойство {@code epd.calc.interior-heating}.
 *
 * <p>В оригинале ({@code helpers.php:348}) надбавка закомментирована и фактически
 * НИКОГДА не применяется ({@code warm_salon = 0}), а по замыслу авторов стояла внутри
 * зимнего блока. Поэтому по умолчанию — {@link #OFF} (паритет с боевыми числами legacy);
 * {@link #WINTER} — как задумано (только когда действует зимний коэффициент маршрута);
 * {@link #ALWAYS} — круглый год (прежнее поведение e-Waybill, MIGRATION.md 5.3 / Вопрос 19).</p>
 */
public enum InteriorHeatingMode {
    /** Не применять (поведение legacy). */
    OFF,
    /** Только в период действия зимнего коэффициента маршрута. */
    WINTER,
    /** Круглый год. */
    ALWAYS
}
