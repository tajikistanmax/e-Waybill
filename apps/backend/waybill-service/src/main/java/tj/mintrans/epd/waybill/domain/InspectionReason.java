package tj.mintrans.epd.waybill.domain;

/**
 * Основание блокировки путевого листа на дорожном контроле.
 *
 * <p>Классификатор, а не свободный текст: инспектор блокирует документ по конкретному
 * нарушению, и это основание должно быть сопоставимым — для статистики надзора, для
 * обжалования перевозчиком и для разблокировки Минтрансом. Свободное описание
 * дополняет основание, но не заменяет его.</p>
 */
public enum InspectionReason {

    /** Предрейсовый медосмотр не пройден либо отметка Т2 отсутствует/просрочена. */
    NO_MED("Не пройден предрейсовый медосмотр"),
    /** Предрейсовый технический контроль не пройден либо отметка Т3 отсутствует. */
    NO_TECH("Не пройден предрейсовый техконтроль"),
    /** Срок действия путевого листа истёк. */
    EXPIRED("Истёк срок действия путевого листа"),
    /** За рулём не тот водитель, на которого выписан лист. */
    DRIVER_MISMATCH("Водитель не соответствует путевому листу"),
    /** Госномер ТС не совпадает с указанным в листе. */
    VEHICLE_MISMATCH("Транспортное средство не соответствует путевому листу"),
    /** Лист не предъявлен, недействителен или предъявлен чужой. */
    NO_DOCUMENT("Путевой лист не предъявлен либо недействителен"),
    /** Нет лицензии перевозчика либо дозвола на международную перевозку. */
    LICENSE("Отсутствует лицензия или дозвол на перевозку"),
    /** Нарушение по грузу: перегруз, опасный груз без разрешения ADR, несоответствие накладной. */
    CARGO("Нарушение условий перевозки груза"),
    /** Нарушение режима труда и отдыха водителя. */
    REGIME("Нарушение режима труда и отдыха"),
    /** Техническая неисправность, выявленная на дороге. */
    TECH_CONDITION("Техническая неисправность транспортного средства"),
    /** Иное основание — описание обязательно. */
    OTHER("Иное основание");

    private final String label;

    InspectionReason(String label) {
        this.label = label;
    }

    /** Человекочитаемое основание — идёт в журнал статусов и в акт. */
    public String label() {
        return label;
    }
}
