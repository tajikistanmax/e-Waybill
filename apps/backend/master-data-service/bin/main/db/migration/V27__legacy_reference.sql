-- Справочники расчётного ядра (перенос схемы ИС «Роҳхат», docs/spec/07-calculations.md §10):
-- марки ТС с нормативами расхода топлива, коэффициенты (зимний/горный/городской/износ),
-- классы водителей. Используются движком расчёта в waybill-service (пакет calc):
-- CoefficientCalculator, FuelNormCalculator.
--
-- ID — BIGINT, как в эталоне: ключи горного/городского справочников осмысленны
-- (на них ссылаются направления перевозок и, косвенно, маршруты).

