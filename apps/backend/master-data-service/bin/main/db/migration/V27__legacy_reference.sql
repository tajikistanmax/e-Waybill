CREATE TABLE brand (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_id               BIGINT       NOT NULL DEFAULT 0,
    -- number: код марки старой системы; 5-я цифра != 0 → наличие прицепа (грузовые формы).
    number                VARCHAR(50),
    name                  VARCHAR(100) NOT NULL,
    model                 VARCHAR(100) NOT NULL DEFAULT '',
    capacity              INTEGER,                 -- мест (пассажирские)
    carrying              DOUBLE PRECISION,        -- грузоподъёмность, т (грузовые)
    cost_services         DOUBLE PRECISION,        -- стоимость услуги (тарификация)
    net_weight            NUMERIC(8, 2) NOT NULL DEFAULT 0,
    -- fuel_100 / fuel_100_dushanbe: JSON-массив нормативов расхода, л/100 км.
    -- элемент: {fuel_id, consumption, ton_for_100, s_for_rais, work_for_hour, consumption_for_special}
    fuel_100              TEXT,
    fuel_100_dushanbe     TEXT,
    fuel_hour             TEXT,                    -- JSON-массив почасовых нормативов, л/час
    fuel_interior_heating DOUBLE PRECISION,        -- отопление салона, л/ч
    tariff_rate           DOUBLE PRECISION,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT now()
);

