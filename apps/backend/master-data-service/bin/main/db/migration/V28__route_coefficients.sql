-- ---------------------------------------------------- тарифы маршрута (нархнома)
CREATE TABLE route_tariff (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id        UUID        NOT NULL REFERENCES route(id) ON DELETE CASCADE,
    fuel_id         SMALLINT,                 -- вид топлива; NULL — для всех
    number          VARCHAR(30),
    type_auto       VARCHAR(50),
    price_per_1_mkm DOUBLE PRECISION NOT NULL, -- цена за 1 машино-км
    price_one_time  DOUBLE PRECISION NOT NULL, -- цена за одну поездку
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_route_tariff_route ON route_tariff (route_id);
