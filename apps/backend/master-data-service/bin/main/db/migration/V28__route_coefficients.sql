-- Phase 2b порта «Роҳхат»: коэффициентные и путевые поля маршрутов (routes),
-- направления перевозок (directions, грузовая ветка) и тарифы маршрута (tariffs → route_tariff).
-- Питают оркестратор расчёта в waybill-service (Phase 3): CoefficientCalculator (пасс./груз.
-- ветки), FuelNormCalculator, PassengerMetrics.
--
-- ВНИМАНИЕ (ловушка эталона, docs/spec/07-calculations.md §1.4.1):
--   route.mountain_coef_value / in_city_coef_value хранят САМО ЗНАЧЕНИЕ коэффициента (5,10,15,20),
--   а direction.mountain_coef_id / in_city_coef_id — КЛЮЧИ справочников mountain_coef / city_coef.

-- ---------------------------------------------------- коэф-поля маршрута
ALTER TABLE route
    ADD COLUMN winter_coef_id           BIGINT,
    ADD COLUMN mountain_coef_value      SMALLINT,   -- ЗНАЧЕНИЕ, не ключ
    ADD COLUMN in_city_coef_value       SMALLINT,   -- ЗНАЧЕНИЕ, не ключ
    ADD COLUMN station_coef             SMALLINT,
    ADD COLUMN road_quality             SMALLINT,
    ADD COLUMN excluding_coef           BOOLEAN NOT NULL DEFAULT FALSE,  -- «душанбинская» ветка без коэффициентов
    ADD COLUMN additional_fuel_100      DOUBLE PRECISION,
    ADD COLUMN additional_fuel          DOUBLE PRECISION,
    ADD COLUMN cond_fuel                DOUBLE PRECISION,
    ADD COLUMN heating_fuel             DOUBLE PRECISION,
    ADD COLUMN distance_a               DOUBLE PRECISION,   -- длина направления «туда», км
    ADD COLUMN distance_b               DOUBLE PRECISION,   -- длина направления «обратно», км
    ADD COLUMN begin_path_a             DOUBLE PRECISION,   -- нулевой пробег «Гашти А»
    ADD COLUMN begin_path_b             DOUBLE PRECISION,
    ADD COLUMN planned_lap              SMALLINT,           -- плановое число рейсов
    ADD COLUMN coe_use_capacity         DOUBLE PRECISION,   -- коэф. использования вместимости
    ADD COLUMN average_length_pass_seat DOUBLE PRECISION;   -- средняя дальность поездки пассажира, км

-- ---------------------------------------------------- направления перевозок (грузовая ветка)
CREATE TABLE direction (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title            VARCHAR(255) NOT NULL,
    number           INTEGER,
    winter_coef_id   BIGINT,     -- ключ fuel_winter_coef
    mountain_coef_id BIGINT,     -- КЛЮЧ mountain_coef
    in_city_coef_id  BIGINT,     -- КЛЮЧ city_coef
    checked          BOOLEAN NOT NULL DEFAULT FALSE,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);
