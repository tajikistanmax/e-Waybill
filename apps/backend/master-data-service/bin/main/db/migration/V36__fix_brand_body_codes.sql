-- Правка кодов кузова марок из V27-сида: первая цифра brand.number задаёт тип расчёта
-- грузового кузова (1/2/4 бортовой=labador, 3 самосвал, 5 спец, 8 спец-движение, 9 без нормы),
-- пятая цифра (>0) — наличие прицепа. В сиде КамАЗ-65115 (самосвал) стоял '60000',
-- Volvo FH 460 (тягач с полуприцепом) — '70000': обе первые цифры не распознавались,
-- срабатывал бортовой фолбэк. Приводим к корректным кодам.
UPDATE brand SET number = '30000' WHERE id = 5 AND number = '60000'; -- КамАЗ 65115 → самосвал
UPDATE brand SET number = '40001' WHERE id = 6 AND number = '70000'; -- Volvo FH 460 → бортовой тягач + прицеп
