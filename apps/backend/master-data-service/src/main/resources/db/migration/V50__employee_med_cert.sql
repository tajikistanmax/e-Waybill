-- Сертификат врача, проводящего медосмотр (§8 QA).
--
-- Проблема: у employee (type=1 «врач/духтур») не было реквизитов сертификата, поэтому на
-- подтверждении медосмотра (waybill-service confirmMed → титул Т2/Т6) нельзя было проверить,
-- действителен ли сертификат самого врача. Добавляем два справочных поля, симметрично тому,
-- как у driver уже хранится med_cert_valid_to (V-миграции driver'а) и проверяется мягко.
--
--   med_cert_number   — номер сертификата/свидетельства врача (для реестра и печатных форм).
--   med_cert_valid_to — срок действия сертификата. Истёкший блокирует confirmMed; NULL (не
--                       заполнен) НЕ блокирует — та же семантика «пробел в справочнике не
--                       блокирует», что у медсправки водителя и страхового полиса ТС.
--
-- Оба поля NULLABLE и БЕЗ DEFAULT: существующие записи сотрудников не трогаем.

ALTER TABLE employee
    ADD COLUMN med_cert_number   VARCHAR(100),
    ADD COLUMN med_cert_valid_to DATE;

COMMENT ON COLUMN employee.med_cert_number   IS 'Номер сертификата врача, проводящего медосмотр (§8 QA)';
COMMENT ON COLUMN employee.med_cert_valid_to IS 'Срок действия сертификата врача; истёкший блокирует confirmMed, NULL не блокирует (§8 QA)';
