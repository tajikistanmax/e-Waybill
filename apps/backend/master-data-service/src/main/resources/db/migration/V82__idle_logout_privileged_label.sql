-- ИБ-13.2.5: у привилегированных ролей (администратор платформы, инспектор, аналитик) тайм-аут
-- бездействия — не больше 30 минут; веб-клиент применяет его сам, даже если настройка выключена
-- (0) или больше. Подпись настройки на странице «Безопасность» говорит об этом, чтобы
-- администратор не удивлялся, почему «0 — выкл.» его всё равно разлогинивает.
update platform_setting
set name_ru = 'Авто-выход при бездействии, мин (0 — выкл.; администратор, инспектор, аналитик — не дольше 30)',
    name_tj = 'Баромади худкор ҳангоми бефаъолиятӣ, дақ (0 — хомӯш; маъмур, нозир, таҳлилгар — на зиёда аз 30)'
where category = 'security' and setting_key = 'idle_logout_minutes';
