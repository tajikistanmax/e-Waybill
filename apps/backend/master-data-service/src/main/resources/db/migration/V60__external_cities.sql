-- Справочник ВНЕШНИХ (зарубежных) городов — источник подсказок для поля «Город» в международных
-- путевых листах и СМР (раньше город вводился свободным текстом). Аналог справочника городов РТ
-- (city, V54), но привязан к стране: country_code = ISO 3166-1 alpha-2 (код элемента классификатора
-- категории COUNTRY, см. V7/V59). Жёсткого FK на classifier нет — там уникальность по паре
-- (category, code), а не по code (та же «мягкая» связь, что и у city.region_id).
-- Двуязычное наименование: name_ru обязательно, name_tj — при наличии (в сиде = name_ru как
-- fallback, по образцу V59; тадж. источника нет).
CREATE TABLE external_city (
    id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    country_code VARCHAR(20)  NOT NULL,
    name_ru      VARCHAR(200) NOT NULL,
    name_tj      VARCHAR(200),
    sort_order   SMALLINT     NOT NULL DEFAULT 0,
    active       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_external_city UNIQUE (country_code, name_ru)
);
CREATE INDEX idx_external_city_country ON external_city (country_code, sort_order);

