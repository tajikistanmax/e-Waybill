-- Справочник городов/районов (перенос из боевого MinTransRT /city, 69 записей).
-- Привязан к региону (region_id 1..7 — те же коды, что region.* во фронте и organization.region_id).
-- Используется как источник подсказок для поля «Город» организации.
CREATE TABLE city (
    id         UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    region_id  SMALLINT     NOT NULL,
    code       VARCHAR(5)   NOT NULL,
    name       VARCHAR(150) NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_city_region_code UNIQUE (region_id, code),
    CONSTRAINT city_region_range CHECK (region_id BETWEEN 1 AND 7)
);
CREATE INDEX idx_city_region ON city (region_id);

