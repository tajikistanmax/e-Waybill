-- Классификаторы (справочники) для международных и опасных перевозок:
-- страны, классы опасных грузов ADR, виды дозволов E-PERMIT. Обобщённая схема
-- (category) — расширяется новыми категориями без изменения структуры.

CREATE TABLE classifier (
    id         UUID PRIMARY KEY,
    category   VARCHAR(30)  NOT NULL,   -- COUNTRY | ADR_CLASS | PERMIT_TYPE
    code       VARCHAR(20)  NOT NULL,   -- ISO-код страны / номер класса / код дозвола
    name_ru    VARCHAR(200) NOT NULL,
    name_tj    VARCHAR(200),
    sort_order SMALLINT     NOT NULL DEFAULT 0,
    active     BOOLEAN      NOT NULL DEFAULT TRUE,
    UNIQUE (category, code)
);

CREATE INDEX idx_classifier_category ON classifier (category, sort_order);

