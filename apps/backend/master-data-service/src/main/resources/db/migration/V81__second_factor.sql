-- Второй фактор входа (TOTP) — находка 27 AUDIT.md.
--
-- Признак «второй фактор обязателен» перенесён из Keycloak ещё в V76 (totp_required у admin,
-- inspector, analyst), но проверки не было: после отказа от Keycloak эти роли входили одним
-- паролем. Здесь — всё, что нужно для настоящей проверки.

-- Назначение одноразового ключа. В одной таблице лежат три разных ключа: токен обновления
-- сессии, ключ смены временного пароля и ключ второго шага входа (после верного пароля, до
-- кода). Раньше их различали косвенно (по признаку «пароль временный»), и ключ второго шага
-- можно было бы предъявить как токен обновления — то есть войти, не вводя код. Теперь каждая
-- точка принимает только ключи своего назначения. Существующие записи — токены обновления.
alter table auth_refresh_token
    add column purpose varchar(16) not null default 'REFRESH';

-- Секрет, выданный при первой настройке, но ещё не подтверждённый кодом. Становится
-- totp_secret только после первого верного кода — иначе пользователь, не успевший
-- отсканировать QR-код, остался бы без входа.
alter table app_user add column totp_pending_secret varchar(64);
-- Шаг времени последнего принятого кода: тот же код дважды не принимается.
alter table app_user add column totp_last_step bigint;
-- Когда второй фактор подключён (для карточки пользователя и аудита).
alter table app_user add column totp_enrolled_at timestamptz;
