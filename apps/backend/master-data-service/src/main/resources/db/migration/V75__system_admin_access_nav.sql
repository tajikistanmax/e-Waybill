-- Раздел «Доступы» администратору платформы.
--
-- Учётные записи заводятся на странице /company/access. Бэкенд разрешает это трём ролям
-- (SYSTEM_ADMIN, COMPANY_ADMIN, BRANCH_ADMIN — см. OrgUserController), но в матрице доступа
-- разделов у SYSTEM_ADMIN ключа `access` не было. Меню строится из этой таблицы, поэтому
-- у администратора платформы пункта «Доступы» в меню НЕ БЫЛО вообще: страница открывалась
-- только вводом адреса вручную. Фактически администратор не мог завести пользователя —
-- в том числе первого администратора новой компании-перевозчика (роль COMPANY_ADMIN выдаёт
-- только он). Находка владельца 23.09.2026 при приёмке.
--
-- Ключ добавляется в конец, порядок остальных разделов не меняется.

update role_access
set nav_keys = nav_keys || ',access'
where role = 'SYSTEM_ADMIN'
  and nav_keys not like '%access%';
